"""
Trae del EA Opportunities Board (effectivealtruism.org/opportunities) las fellowships, pasantías,
cursos, fondos, eventos y voluntariados, sin los empleos, y reescribe data/raw/ea-oportunidades.json.
La página incluye todos sus datos en el stream RSC de Next.js (self.__next_f), así que no hace
falta navegador ni API. Solo librería estándar.

    python scripts/actualizar_ea.py          actualiza el archivo
    python scripts/actualizar_ea.py --seco   muestra cuántas hay, sin guardar

Después corre `npm run data:import` para regenerar el catálogo.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "raw" / "ea-oportunidades.json"
URL = "https://www.effectivealtruism.org/opportunities"
JOB_TYPES = {"Full-time", "Part-time"}
DISCLAIMER = re.compile(r"\s*\*This text was generated by AI.*$", re.S)


PUSH = re.compile(r'self\.__next_f\.push\(\[1,("(?:[^"\\]|\\.)*")\]\)')
ROW_ID = re.compile(rb"([0-9a-f]+):")


def text_rows(raw: bytes) -> dict[str, str]:
    """Walks the RSC rows. A text row ("id:T<hex length>,<text>") has no closing newline,
    so the next row starts right after its last byte; every other row ends at a newline."""
    texts, pos = {}, 0
    while pos < len(raw):
        m = ROW_ID.match(raw, pos)
        if m and raw[m.end() : m.end() + 1] == b"T":
            comma = raw.index(b",", m.end())
            size = int(raw[m.end() + 1 : comma], 16)
            texts["$" + m.group(1).decode()] = raw[comma + 1 : comma + 1 + size].decode("utf-8", "replace")
            pos = comma + 1 + size
        else:
            newline = raw.find(b"\n", pos)
            pos = len(raw) if newline < 0 else newline + 1
    return texts


def fetch() -> list[dict]:
    """The page is a Next.js App Router page: the data travels in the RSC stream pushed to
    self.__next_f. The opportunities are an inline JSON array there; long texts are separate
    rows ("2c:T<byte length in hex>,<text>") that the array points to as "$2c"."""
    req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0 (Apliko; catalogo de becas)"})
    page = urllib.request.urlopen(req, timeout=60).read().decode("utf-8")
    stream = "".join(json.loads(m.group(1)) for m in PUSH.finditer(page))
    start = stream.find('"opportunities":[')
    if start < 0:
        raise RuntimeError("La página ya no trae la lista de oportunidades: revisa si cambió su estructura.")
    opportunities, _ = json.JSONDecoder().raw_decode(stream, start + len('"opportunities":'))

    texts = text_rows(stream.encode("utf-8"))

    def resolve(value):
        if isinstance(value, str) and value.startswith("$"):
            return texts.get(value)  # "$undefined" and unknown references become None
        return value

    return [{key: resolve(value) for key, value in o.items()} for o in opportunities]


def to_row(o: dict) -> dict:
    return {
        "title": o["title"].strip(),
        "organization": ", ".join(o.get("organization") or []),
        "types": o.get("opportunityTypes") or [],
        "causeAreas": o.get("causeAreas") or [],
        "location": (o.get("location") or "").strip(),
        "locationFilter": o.get("locationFilter") or [],
        "deadline": o.get("applicationDeadline") or None,
        "pay": o.get("salaryOriginal") or None,
        "link": o["applicationLink"].strip(),
        "description": DISCLAIMER.sub("", o.get("description") or "").strip(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seco", action="store_true", help="no guarda nada")
    args = parser.parse_args()

    opportunities = fetch()
    keep = [o for o in opportunities if set(o.get("opportunityTypes") or []) - JOB_TYPES and o.get("applicationLink")]
    rows = [to_row(o) for o in sorted(keep, key=lambda o: o.get("createdAt") or "", reverse=True)]
    # A near-empty result means the page changed, not that the board emptied: keep the old file.
    if len(rows) < 20:
        print(f"Solo {len(rows)} oportunidades: no reescribo {OUT.name} por si la página cambió.", file=sys.stderr)
        return 1

    print(f"{len(opportunities)} en el tablero, {len(rows)} sin empleos.")
    if args.seco:
        return 0
    OUT.write_text("[\n" + ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows) + "\n]\n", encoding="utf-8", newline="\n")
    print(f"Guardado {OUT.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
